/* serenity_menu_v1 — server side (pure C).
 *
 * This is the protocol bridge only.  It does NOT know about GUI::Menu or
 * WindowServer: every request is forwarded through serenity_menu_callbacks to
 * main.cpp, which owns the native GUI::Menu objects and their WS IPC.
 * Keeping this file pure C matches wlroots_proto.c (WLR_USE_UNSTABLE, C23).
 *
 * P0 scope: register the global, accept create_menu / add_item / add_separator
 * / popup / dismiss / destroy, and expose send_* helpers so the C++ side can
 * push activated / dismissed / hovered back to the GTK client.
 */
#ifndef WLR_USE_UNSTABLE
#  define WLR_USE_UNSTABLE
#endif
#include "serenity_menu_proto.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <wayland-server-core.h>
#include <wayland-server-protocol.h> /* WL_PROTOCOL_ERROR_NONE, wl_surface_interface */

/* wayland-scanner server-header: send_* helpers, request vtable structs and
 * the two wl_interface declarations.  Generated by protocol/gen.sh. */
#include "protocol/serenity-menu-v1-server.h"

struct serenity_menu_proto {
    struct wl_global* global;
    struct wl_display* display;
    struct serenity_menu_callbacks cb;
    struct wl_list menus; /* serenity_menu_node.link */
};

struct serenity_menu_node {
    struct wl_resource* resource;
    struct wl_client* client;
    struct serenity_menu_proto* proto;
    void* native; /* GUI::Menu*, owned by main.cpp */
    struct wl_list link;
};

/* -------------------------------------------------------------- helpers -- */

static struct serenity_menu_node* node_from_resource(struct wl_resource* r)
{
    return (struct serenity_menu_node*) wl_resource_get_user_data(r);
}

static void node_destroy_notify(struct wl_resource* resource)
{
    struct serenity_menu_node* n = node_from_resource(resource);
    if (!n)
        return;
    if (n->proto->cb.destroy)
        n->proto->cb.destroy(n->proto->cb.user, n);
    wl_list_remove(&n->link);
    free(n);
}

/* --------------------------------------------------------- menu requests -- */

static void menu_destroy(struct wl_client* client, struct wl_resource* resource)
{
    (void) client;
    wl_resource_destroy(resource);
}

static void menu_add_item(struct wl_client* client, struct wl_resource* resource,
    uint32_t identifier, const char* text, const char* shortcut,
    uint32_t enabled, uint32_t checkable, uint32_t checked,
    struct wl_resource* submenu)
{
    struct serenity_menu_node* n = node_from_resource(resource);
    (void) client;
    if (!n || !n->proto->cb.add_item)
        return;
    void* sub = submenu ? (void*) node_from_resource(submenu) : NULL;
    n->proto->cb.add_item(n->proto->cb.user, n, identifier,
        text ? text : "", shortcut ? shortcut : "",
        enabled != 0, checkable != 0, checked != 0, sub);
}

static void menu_add_separator(struct wl_client* client, struct wl_resource* resource)
{
    struct serenity_menu_node* n = node_from_resource(resource);
    (void) client;
    if (n && n->proto->cb.add_separator)
        n->proto->cb.add_separator(n->proto->cb.user, n);
}

static void menu_add_icon(struct wl_client* client, struct wl_resource* resource,
    uint32_t identifier, int32_t fd, uint32_t width, uint32_t height, uint32_t stride)
{
    struct serenity_menu_node* n = node_from_resource(resource);
    (void) client;
    if (n && n->proto->cb.add_icon)
        n->proto->cb.add_icon(n->proto->cb.user, n, identifier, fd, width, height, stride);
    else
        close(fd);
}

static void menu_update_item(struct wl_client* client, struct wl_resource* resource,
    uint32_t identifier, uint32_t enabled, uint32_t checked)
{
    struct serenity_menu_node* n = node_from_resource(resource);
    (void) client;
    if (n && n->proto->cb.update_item)
        n->proto->cb.update_item(n->proto->cb.user, n, identifier, enabled != 0, checked != 0);
}

static void menu_popup(struct wl_client* client, struct wl_resource* resource, uint32_t serial)
{
    struct serenity_menu_node* n = node_from_resource(resource);
    (void) client;
    if (n && n->proto->cb.popup)
        n->proto->cb.popup(n->proto->cb.user, n, serial);
}

static void menu_dismiss(struct wl_client* client, struct wl_resource* resource)
{
    struct serenity_menu_node* n = node_from_resource(resource);
    (void) client;
    if (n && n->proto->cb.dismiss)
        n->proto->cb.dismiss(n->proto->cb.user, n);
}

static const struct serenity_menu_v1_interface menu_impl = {
    .add_item = menu_add_item,
    .add_separator = menu_add_separator,
    .add_icon = menu_add_icon,
    .update_item = menu_update_item,
    .popup = menu_popup,
    .dismiss = menu_dismiss,
    .destroy = menu_destroy,
};

/* ------------------------------------------------------ manager requests -- */

static void manager_create_menu(struct wl_client* client, struct wl_resource* manager,
    uint32_t id, struct wl_resource* surface,
    int32_t x, int32_t y, int32_t anchor_width, int32_t anchor_height)
{
    struct serenity_menu_proto* p =
        (struct serenity_menu_proto*) wl_resource_get_user_data(manager);
    struct serenity_menu_node* n;

    n = (struct serenity_menu_node*) calloc(1, sizeof(*n));
    if (!n) {
        wl_client_post_no_memory(client);
        return;
    }
    n->proto = p;
    n->client = client;
    n->resource = wl_resource_create(client, &serenity_menu_v1_interface,
        wl_resource_get_version(manager), id);
    if (!n->resource) {
        wl_client_post_no_memory(client);
        free(n);
        return;
    }
    wl_resource_set_implementation(n->resource, &menu_impl, n, node_destroy_notify);
    wl_list_insert(&p->menus, &n->link);

    if (p->cb.create_menu)
        p->cb.create_menu(p->cb.user, n, surface, x, y, anchor_width, anchor_height);
}

static void manager_destroy(struct wl_client* client, struct wl_resource* manager)
{
    (void) client;
    wl_resource_destroy(manager);
}

static const struct serenity_menu_manager_v1_interface manager_impl = {
    .create_menu = manager_create_menu,
    .destroy = manager_destroy,
};

static void bind_manager(struct wl_client* client, void* data, uint32_t version, uint32_t id)
{
    struct serenity_menu_proto* p = (struct serenity_menu_proto*) data;
    struct wl_resource* r = wl_resource_create(client,
        &serenity_menu_manager_v1_interface, version, id);
    if (!r) {
        wl_client_post_no_memory(client);
        return;
    }
    wl_resource_set_implementation(r, &manager_impl, p, NULL);
    fprintf(stderr, "ws-menu: client bound serenity_menu_manager_v1 v%u\n", version);
}

/* ------------------------------------------------------------- public API -- */

struct serenity_menu_proto* serenity_menu_proto_create(struct wl_display* display,
    const struct serenity_menu_callbacks* cb)
{
    struct serenity_menu_proto* p = (struct serenity_menu_proto*) calloc(1, sizeof(*p));
    if (!p)
        return NULL;
    p->display = display;
    if (cb)
        p->cb = *cb;
    wl_list_init(&p->menus);
    p->global = wl_global_create(display, &serenity_menu_manager_v1_interface, 1, p, bind_manager);
    if (!p->global) {
        fprintf(stderr, "ws-menu: failed to create serenity_menu_manager_v1 global\n");
        free(p);
        return NULL;
    }
    fprintf(stderr, "ws-menu: serenity_menu_manager_v1 global ready\n");
    return p;
}

void serenity_menu_proto_destroy(struct serenity_menu_proto* p)
{
    if (!p)
        return;
    if (p->global)
        wl_global_destroy(p->global);
    free(p);
}

void* serenity_menu_native(void* menu)
{
    return menu ? ((struct serenity_menu_node*) menu)->native : NULL;
}

void serenity_menu_set_native(void* menu, void* native)
{
    if (menu)
        ((struct serenity_menu_node*) menu)->native = native;
}

void serenity_menu_send_activated(void* menu, uint32_t identifier)
{
    struct serenity_menu_node* n = (struct serenity_menu_node*) menu;
    if (n && n->resource)
        serenity_menu_v1_send_activated(n->resource, identifier);
}

void serenity_menu_send_dismissed(void* menu)
{
    struct serenity_menu_node* n = (struct serenity_menu_node*) menu;
    if (n && n->resource)
        serenity_menu_v1_send_dismissed(n->resource);
}

void serenity_menu_send_hovered(void* menu, uint32_t identifier, uint32_t entered)
{
    struct serenity_menu_node* n = (struct serenity_menu_node*) menu;
    if (n && n->resource)
        serenity_menu_v1_send_hovered(n->resource, identifier, entered);
}

void serenity_menu_flush(struct serenity_menu_proto* p)
{
    if (p && p->display)
        wl_display_flush_clients(p->display);
}
