#!/usr/bin/env python3
"""Embed the Vista icon set into LibDesktop as raw RGBA8888 pixel data.

Input : Base/res/icons/vista/{16x16,32x32}/*.png  (see gen-vista-icons.py)
Output: Userland/Libraries/LibDesktop/DesktopIcons.{h,cpp}

Only 6 of the 32x32 icons are embedded (the application logos that actually get
used as window icons); embedding all 18 at both sizes would roughly double the
object size for no benefit.

Usage: scripts/port/embed-desktop-icons.py
"""

import os
import struct
import subprocess
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC16 = os.path.join(ROOT, 'Base/res/icons/vista/16x16')
SRC32 = os.path.join(ROOT, 'Base/res/icons/vista/32x32')
OUT_H = os.path.join(ROOT, 'Userland/Libraries/LibDesktop/DesktopIcons.h')
OUT_CPP = os.path.join(ROOT, 'Userland/Libraries/LibDesktop/DesktopIcons.cpp')

LOGOS_32 = [
    'app-file-manager',
    'app-terminal',
    'app-display-settings',
    'app-image-viewer',
    'app-help',
    'desktop',
]


def read_png_rgba(path, expect):
    """Decode a PNG to raw RGBA bytes using ImageMagick (no Python image libs)."""
    raw = subprocess.check_output(['convert', path, '-depth', '8', 'RGBA:-'])
    if len(raw) != expect * expect * 4:
        raise SystemExit(f'{path}: expected {expect}x{expect} RGBA, got {len(raw)} bytes')
    return raw


def emit_array(name, data):
    ident = 's_' + name.replace('-', '_')
    body = ','.join(str(b) for b in data)
    return f'static u8 const {ident}[{len(data)}] = {{ {body} }};', ident


def main():
    names16 = sorted(f[:-4] for f in os.listdir(SRC16) if f.endswith('.png'))
    names32 = [n for n in LOGOS_32 if os.path.exists(os.path.join(SRC32, n + '.png'))]

    arrays, entries16, entries32 = [], [], []
    for n in names16:
        data = read_png_rgba(os.path.join(SRC16, n + '.png'), 16)
        arr, ident = emit_array(n, data)
        arrays.append(arr)
        entries16.append(f'    {{ "{n}"sv, {{ {ident}, sizeof({ident}) }} }},')

    arrays.append('')
    for n in names32:
        data = read_png_rgba(os.path.join(SRC32, n + '.png'), 32)
        arr, ident = emit_array('logo_' + n, data)
        arrays.append(arr)
        entries32.append(f'    {{ "{n}"sv, {{ {ident}, sizeof({ident}) }} }},')

    header = '''/*
 * Generated by scripts/port/embed-desktop-icons.py - do not edit.
 *
 * System-wide UI icons and application logos embedded as raw RGBA8888 pixels.
 * Because the data lives in this library's .rodata, components can draw their
 * chrome without touching /res, resource:// or the image-decoder service.
 */

#pragma once

#include <AK/StringView.h>
#include <LibGfx/Bitmap.h>

namespace Desktop {

// 16x16 chrome icon, or nullptr if the name is not embedded.
RefPtr<Gfx::Bitmap const> icon(StringView name);

// 32x32 application logo, or nullptr if the name is not embedded.
RefPtr<Gfx::Bitmap const> app_logo(StringView name);

}
'''

    source = '''/*
 * Generated by scripts/port/embed-desktop-icons.py - do not edit.
 */

#include <LibDesktop/DesktopIcons.h>
#include <AK/Span.h>
#include <string.h>

namespace Desktop {

namespace {

struct IconEntry {
    StringView name;
    ReadonlyBytes rgba;
};

''' + '\n'.join(arrays) + '''

IconEntry const s_icons16[] = {
''' + '\n'.join(entries16) + '''
};

IconEntry const s_logos32[] = {
''' + '\n'.join(entries32) + '''
};

RefPtr<Gfx::Bitmap const> make_bitmap(ReadonlyBytes rgba, int size)
{
    // LibGfx only supports BGRx8888 / BGRA8888 storage in get_pixel(),
    // solid_color() and friends. Creating an RGBA8888 bitmap here made
    // GUI::Button::paint_event() hit VERIFY_NOT_REACHED() in Bitmap.h.
    // Convert the embedded RGBA bytes to BGRA while copying.
    auto bitmap = Gfx::Bitmap::create(Gfx::BitmapFormat::BGRA8888, { size, size }).release_value();
    for (int y = 0; y < size; ++y) {
        auto* dst = bitmap->scanline_u8(y);
        auto const* src = rgba.data() + static_cast<size_t>(y) * size * 4;
        for (int x = 0; x < size; ++x) {
            dst[x * 4 + 0] = src[x * 4 + 2]; // B
            dst[x * 4 + 1] = src[x * 4 + 1]; // G
            dst[x * 4 + 2] = src[x * 4 + 0]; // R
            dst[x * 4 + 3] = src[x * 4 + 3]; // A
        }
    }
    return bitmap;
}

}

RefPtr<Gfx::Bitmap const> icon(StringView name)
{
    for (auto const& entry : s_icons16) {
        if (entry.name == name)
            return make_bitmap(entry.rgba, 16);
    }
    return nullptr;
}

RefPtr<Gfx::Bitmap const> app_logo(StringView name)
{
    for (auto const& entry : s_logos32) {
        if (entry.name == name)
            return make_bitmap(entry.rgba, 32);
    }
    return nullptr;
}

}
'''

    open(OUT_H, 'w', encoding='utf-8').write(header)
    open(OUT_CPP, 'w', encoding='utf-8').write(source)
    print(f'embedded {len(names16)} 16x16 icons, {len(names32)} 32x32 logos')


if __name__ == '__main__':
    main()
